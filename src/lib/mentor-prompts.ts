export function getSystemPrompt(practice: MentorPractice): string {
  if (practice === 'free') return BASE_PROMPT;
  return `${BASE_PROMPT}\n\n${MODE_PROMPTS[practice]}`;
}

export function mapDayPracticeToMentor(
  id: 'phronesis' | 'threeQuestions' | 'empathy' | 'languageGame',
): MentorPractice {
  switch (id) {
    case 'phronesis':
      return 'phronesis';
    case 'empathy':
      return 'empathy';
    case 'languageGame':
      return 'language-game';
    case 'threeQuestions':
      return 'three-questions';
    default:
      return 'free';
  }
}
